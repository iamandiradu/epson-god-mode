"""Printer model database: what is at which EEPROM address, per model family.

All model knowledge lives in ``egm/data/models.json`` (generated by
``tools/build_models.py``); this module only loads it and answers questions.
Nothing here talks to a printer.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from functools import lru_cache
from importlib.resources import files
from typing import Iterable, Optional

Coverage = str  # "full" | "partial" | "readonly" | "none"

COVERAGE_LABELS = {
    "full": "Full: waste counters readable, reset sequence and write key known",
    "partial": "Partial: counters and reset known, but no write key (writes will likely be refused)",
    "readonly": "Read-only: EEPROM can be read, no reset data for this family",
    "none": "No EEPROM access data",
}


@dataclass(frozen=True)
class WasteCounter:
    addresses: list[int]
    max: Optional[int]
    extra: list[dict] = field(default_factory=list)  # {address, mask, shift}
    min: int = 0

    @property
    def all_addresses(self) -> list[int]:
        return list(self.addresses) + [e["address"] for e in self.extra]

    def decode(self, cells: dict[int, int]) -> int:
        """Little-endian over ``addresses``; ``extra`` nibbles become the next
        most-significant bits."""
        value = 0
        for i, a in enumerate(self.addresses):
            value |= (cells.get(a, 0) & 0xFF) << (8 * i)
        shift = 8 * len(self.addresses)
        for e in self.extra:
            part = (cells.get(e["address"], 0) & e["mask"]) >> e["shift"]
            value |= part << shift
            shift += 8  # one filtered byte -> at most 8 bits
        return value

    def percent(self, cells: dict[int, int]) -> Optional[float]:
        if not self.max:
            return None
        return round(100.0 * self.decode(cells) / self.max, 2)


@dataclass(frozen=True)
class Family:
    name: str
    read_key: list[int]
    write_key: Optional[str]  # plain text key, e.g. "Maribaya"; shifted +1 on the wire
    readlen: int
    sendlen: int
    coverage: Coverage
    models: list[str]
    waste_counters: list[WasteCounter]
    waste_reset: dict[int, int]
    waste_reset_close: list[dict]
    stats: list[dict]
    dates: list[dict]
    fatal_registers: list[dict]
    fatal_tables: list[str]
    cleaning: list[dict]
    serial: list[int]
    head_id: list[int]
    memory: dict
    extra_operations: list[dict]
    usb_id: list[int]
    net_id: list[int]

    @property
    def wire_write_key(self) -> Optional[bytes]:
        if not self.write_key:
            return None
        return bytes(0 if ord(c) == 0 else (ord(c) + 1) & 0xFF for c in self.write_key)

    @property
    def can_write(self) -> bool:
        return bool(self.write_key)

    @property
    def reset_masks(self) -> Optional[dict[int, int]]:
        """Completion step after the counter writes: ``{address: AND mask}``.

        Only the exact ``query A $v / $v : $v M & / write A $v`` shape is
        accepted; anything else returns None so callers refuse the reset."""
        import re as _re
        out: dict[int, int] = {}
        for c in self.waste_reset_close:
            q = _re.fullmatch(r"(0x[0-9a-fA-F]+)\s+(\$\w+)", c.get("query", ""))
            if not q:
                return None
            var = _re.escape(q.group(2))
            op = _re.fullmatch(var + r"\s*:\s*" + var + r"\s+(0x[0-9a-fA-F]+)\s+&", c.get("var", ""))
            w = _re.fullmatch(r"(0x[0-9a-fA-F]+)\s+" + var, c.get("write", ""))
            if not op or not w or int(w.group(1), 16) != int(q.group(1), 16):
                return None
            out[int(q.group(1), 16)] = int(op.group(1), 16)
        return out

    @property
    def memory_range(self) -> range:
        low = int(self.memory.get("low", 0))
        high = int(self.memory.get("high", 0xFF))
        return range(low, high + 1)

    def interesting_addresses(self) -> list[int]:
        """Every address the database names for this family (backup set)."""
        out: set[int] = set()
        for c in self.waste_counters:
            out.update(c.all_addresses)
        out.update(self.waste_reset.keys())
        for s in self.stats:
            regs = s["registers"]
            if regs and isinstance(regs[0], list):
                for r in regs:
                    out.update(r)
            else:
                out.update(regs)
        for d in self.dates:
            out.update(d["registers"])
        for f in self.fatal_registers:
            out.update(f["registers"])
        out.update(self.serial)
        out.update(self.head_id)
        for e in self.extra_operations:
            out.update(int(k) for k in e["write"])
        return sorted(out)


@dataclass(frozen=True)
class Model:
    name: str
    family: Family
    title: str
    model_string: str  # what the printer reports as MDL in its IEEE 1284 device id
    featured: bool
    verified: Optional[str]  # None | "community" | "egm"
    verified_note: Optional[str]
    alias_of: Optional[str] = None
    in_epson_print_conf: bool = False

    @property
    def coverage(self) -> Coverage:
        return self.family.coverage


def _family(name: str, raw: dict) -> Family:
    counters = [
        WasteCounter(addresses=c["addresses"], max=c.get("max"), extra=c.get("extra", []),
                     min=c.get("min", 0))
        for c in raw.get("waste_counters", [])
    ]
    return Family(
        name=name,
        read_key=list(raw.get("read_key", [])),
        write_key=raw.get("write_key"),
        readlen=int(raw.get("readlen", 2)),
        sendlen=int(raw.get("sendlen", 2)),
        coverage=raw.get("coverage", "none"),
        models=list(raw.get("models", [])),
        waste_counters=counters,
        waste_reset={int(k): int(v) for k, v in raw.get("waste_reset", {}).items()},
        waste_reset_close=raw.get("waste_reset_close", []),
        stats=raw.get("stats", []),
        dates=raw.get("dates", []),
        fatal_registers=raw.get("fatal_registers", []),
        fatal_tables=raw.get("fatal_tables", []),
        cleaning=raw.get("cleaning", []),
        serial=raw.get("serial", []),
        head_id=raw.get("head_id", []),
        memory=raw.get("memory", {"low": 0, "high": 0xFF}),
        extra_operations=raw.get("extra_operations", []),
        usb_id=raw.get("usb_id", []),
        net_id=raw.get("net_id", []),
    )


class ModelDB:
    def __init__(self, data: dict, fatal_codes: dict):
        self.featured_names: list[str] = data.get("featured", [])
        self.popular_names: list[str] = data.get("popular", self.featured_names)
        self.families: dict[str, Family] = {k: _family(k, v) for k, v in data["families"].items()}
        self.models: dict[str, Model] = {}
        for name, m in data["models"].items():
            self.models[name] = Model(
                name=name, family=self.families[m["family"]], title=m.get("title", name),
                model_string=m.get("model_string", ""), featured=bool(m.get("featured")),
                verified=m.get("verified"), verified_note=m.get("verified_note"),
                alias_of=m.get("alias_of"), in_epson_print_conf=bool(m.get("in_epson_print_conf")),
            )
        self.fatal_codes: dict[str, dict[str, dict]] = fatal_codes
        self._by_model_string: dict[str, list[Model]] = {}
        for m in self.models.values():
            self._by_model_string.setdefault(m.model_string.lower(), []).append(m)

    # -- lookups -----------------------------------------------------------
    def get(self, name: str) -> Optional[Model]:
        if not name:
            return None
        key = name.strip()
        if key in self.models:
            return self.models[key]
        norm = _normalize(key)
        for n, m in self.models.items():
            if _normalize(n) == norm:
                return m
        return None

    def names(self) -> list[str]:
        return sorted(self.models, key=_sort_key)

    def featured(self) -> list[Model]:
        """Every EcoTank model, the popular ones first."""
        return [self.models[n] for n in self.featured_names if n in self.models]

    def popular(self) -> list[Model]:
        """The hand-picked most common models."""
        return [self.models[n] for n in self.popular_names if n in self.models]

    def search(self, text: str) -> list[Model]:
        t = _normalize(text)
        if not t:
            return []
        return [m for n, m in self.models.items() if t in _normalize(n) or t in _normalize(m.title)]

    def detect(self, model_string: str, hint: Optional[str] = None) -> Optional[Model]:
        """Resolve the MDL string from a device id ("L3110 Series") to a Model.

        Several marketing names share one model string (L3110/L3111 both report
        "L3110 Series"). ``hint`` (a name the user typed earlier) wins when it
        is in the same family; otherwise the first/primary name is returned.
        """
        if not model_string:
            return None
        ms = model_string.strip().lower()
        candidates = self._by_model_string.get(ms) or []
        if not candidates:
            base = re.sub(r"\s*series\s*$", "", ms).strip()
            direct = self.get(base.upper())
            if direct:
                return direct
            # "EPSON L3110 Series" / "L3110" substring fallbacks
            for k, lst in self._by_model_string.items():
                if k and (k in ms or ms in k):
                    candidates = lst
                    break
        if not candidates:
            return None
        if hint:
            h = self.get(hint)
            if h and h in candidates:
                return h
        # prefer a featured, non-alias name
        candidates = sorted(candidates, key=lambda m: (m.alias_of is not None, not m.featured, _sort_key(m.name)))
        return candidates[0]

    def fatal_text(self, family: Family, table_kind: str, code: int) -> Optional[dict]:
        """Describe a fatal error code. ``table_kind`` is PRINTER/SCANNER/GENERAL."""
        for tname in family.fatal_tables:
            table = self.fatal_codes.get(tname, {})
            for k, v in table.items():
                if v.get("type") == table_kind and int(k, 0) == code:
                    return {"code": k, **v}
        return None


def _normalize(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower().replace("epson", ""))


def _sort_key(name: str):
    m = re.match(r"([A-Za-z\- ]*)(\d*)(.*)", name)
    if not m:
        return (name, 0, "")
    return (m.group(1), int(m.group(2) or 0), m.group(3))


@lru_cache(maxsize=1)
def load() -> ModelDB:
    pkg = files("egm") / "data"
    data = json.loads((pkg / "models.json").read_text(encoding="utf-8"))
    fatal = json.loads((pkg / "fatal_codes.json").read_text(encoding="utf-8"))
    return ModelDB(data, fatal)


def iter_featured_names() -> Iterable[str]:
    return [m.name for m in load().featured()]
